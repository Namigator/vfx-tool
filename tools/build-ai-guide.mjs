// The registry has no category or node-level description (only ports/params), so both live here. The test asserts
// every registry node type has an entry, so adding a node without describing it fails the gate.
// Node categories, node descriptions and parameter descriptions live in src/graph/nodeDocs.ts (shared with the editor).
const CATEGORIES = NODE_CATEGORIES;
const isAudioType = (t) => t.startsWith('Audio');

const editText = { live: 'live: applies immediately while playing', resample: 'resample: re-simulates the effect' };
const disabledText = {
  empty: 'disabled = produces nothing', bypass: 'disabled = passes its input straight through', fallback: 'disabled = consumers use their own literal',
  protected: 'cannot be disabled',
};

function buildNodes() {
  const specs = [...createRegistry().values()];
  const byCat = CATEGORIES.map(([name, blurb], i) => ({ name, blurb, list: specs.filter(s => (NODE_INFO[s.type]?.[0] ?? -1) === i) }));
  const orphan = specs.filter(s => !NODE_INFO[s.type]);
  if (orphan.length) byCat.push({ name: 'Uncategorised', blurb: 'Nodes without an entry in tools/build-ai-guide.mjs NODE_INFO.', list: orphan });
  const toc = [], body = [];
  for (const cat of byCat) {
    if (!cat.list.length) continue;
    toc.push([cat.name, slug(cat.name)]);
    body.push(`## ${cat.name}\n\n${cat.blurb}\n`);
    for (const s of cat.list) {
      toc.push([s.type, slug(s.type), 1]);
      const cap = s.capabilities.find(c => c.startsWith('portability:'))?.slice(12) ?? 'approximation';
      const isAudio = isAudioType(s.type);
      if (!NODE_INFO[s.type]) gaps.nodes.push(s.type);
      const info = NODE_INFO[s.type]?.[1] ?? '(no description written yet)';
      const portRows = (list) => list.map(p => [code(p.id), p.label, p.type, p.cardinality === 'many' ? 'many' : 'one', p.required ? 'yes' : 'no', p.domains?.length ? p.domains.join('/') : '—']);
      const paramRows = s.parameters.map(p => {
        const description = p.description || PARAM_DESC[`${s.type}.${p.id}`] || (p.id === 'renderOrderOffset' ? 'Draw order tweak: higher draws on top of lower among layers of the same blend (-32..32).' : '');
        if (!description) gaps.params.push(`${s.type}.${p.id}`);
        const drive = valueTypeToPortType(p.type);
        const constraint = p.type === 'curve' ? `${range(p.min, p.max)} (${p.curveDomain ?? 'normalized'} curve)` : p.type === 'registeredRecord' ? `record ${p.recordType}` : range(p.min, p.max, p.step);
        return [code(p.id), p.label, p.type, unitText(p.unit), code(fmtValue(p.default)), constraint, p.choices ? p.choices.join(', ') : '—', p.editPolicy, p.domains.join('/'), drive ? `${drive}` : '—', description || '—'];
      });
      body.push(`### ${s.type}\n\n${isAudio ? '**Sound (parked).** ' : ''}${info}\n\n` +
        `- Category: ${cat.name}; portability: ${cap}; ${disabledText[s.disabledBehavior]}${s.bypass ? ` (${s.bypass.input} -> ${s.bypass.output})` : ''}; definition version ${s.definitionVersion}.\n\n` +
        `**Inputs**\n\n${s.inputs.length ? table(['id', 'label', 'type', 'connections', 'required', 'domains'], portRows(s.inputs)) : 'None declared. (Number/boolean/colour/vector parameters can still be driven, see the Drive column.)\n'}\n` +
        `**Outputs** (each output can feed any number of inputs)\n\n${s.outputs.length ? table(['id', 'label', 'type', 'domains'], s.outputs.map(p => [code(p.id), p.label, p.type, p.domains?.length ? p.domains.join('/') : '—'])) : 'None.\n'}\n` +
        `**Parameters**\n\n${s.parameters.length ? table(['id', 'label', 'type', 'unit', 'default', 'range', 'choices', 'edit', 'domains', 'drive', 'description'], paramRows) : 'None.\n'}`);
    }
  }
  const intro = `Every node type in the registry (${specs.length} types, definition version 1), grouped by role. Node ids in a document are free-form; the **type** is what you pick. Set parameters with the MCP tools (see mcp-tools.md) using the parameter **id** and a value of the listed type and range.

How to read the tables:
- **Ports** carry typed connections: an output connects only to an input of the same port type (and unit). \`connections: many\` inputs accept several links (they are ordered); \`one\` accepts a single link. Outputs always fan out: one output (a particle chain, an event, a path set) can feed any number of inputs, e.g. the same Emitter particles into a renderer and into ParticleEvents. \`required: yes\` inputs must be connected or compile reports an error.
- **Unit** values: meter, second, tick (60 per second), radian, metersPerSecond, metersPerSecondSquared, hertz, perSecond, linearGain, normalized (0..1), none. A connection must match the unit exactly (use ScalarMath/Constant with a Unit to convert).
- **default** shows curves and gradients compactly (\`curve normalized/linear: 0:1 1:0\`, \`gradient: 0:#FFFFFF 1:#FF8000\`). The JSON you pass to vfx_set_params / vfx_add_node is: curve \`{ "domain": "normalized", "interpolation": "linear", "keys": [{ "x": 0, "y": 1 }, { "x": 1, "y": 0 }] }\` (2-16 keys, x ascending); gradient \`{ "stops": [{ "position": 0, "color": { "srgb": "#FFFFFF", "alpha": 1 } }, { "position": 1, "color": { "srgb": "#FF8000", "alpha": 0 } }] }\` (2-8 stops). Colours everywhere are \`{ "srgb": "#RRGGBB", "alpha": 1 }\`. \`vfx_describe_node_type\` shows the exact default JSON.
- **range** is the accepted min..max (values outside are rejected, never clamped). Vector parameters list one bound for every component.
- **drive**: number, integer, boolean, colour, vec2, vec3 and quaternion parameters are also implicit input ports named after the parameter; connect a signal node (Constant, RandomRange, ScalarMath, Oscillator, Time, EffectTimeCurve, PublicParameter) whose output unit and evaluation domain match. \`domains\` lists which signal domains the parameter accepts (constant = fixed; effectTime = varies over effect time; normalizedAge = varies over particle life; pathU = varies along a path). Integer parameters accept only constant sources. Curve/gradient parameters take a Curve/Gradient node (curveValue/gradientValue). Enum and string parameters cannot be driven.
- **edit**: live = a change applies instantly while playing; resample = the effect is re-simulated after a change (still fast, but not per-frame).
- **Disabled behaviour**: what a disabled node does (empty = nothing, bypass = passes its input through, fallback = consumers use their literal).
- **Portability**: core (exports faithfully), approximation (exports approximately), enhancement (preview only) relative to the Roblox export.
- Defaults are the values a freshly created node gets when a parameter is not given.`;
  save('nodes.md', file('nodes.md', 'Node reference', intro, toc, body.join('\n')));
}

