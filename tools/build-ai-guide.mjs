function buildComponents() {
  const comps = [...COMPONENT_TEMPLATES];
  const fam = ['Fire', 'Lightning', 'Water', 'Ice', 'Earth', 'Wind', 'Poison', 'Shadow', 'Light', 'Energy', 'Generic'];
  const toc = [], body = [];
  for (const f of fam) {
    const list = comps.filter(c => familyOf(c.id) === f);
    if (!list.length) continue;
    toc.push([`${f} (${list.length})`, slug(f)]);
    body.push(`## ${f}\n`);
    for (const c of list) {
      const title = `${c.id}`;
      toc.push([`${c.id} — ${c.label}`, slug(title), 1]);
      const types = new Map();
      for (const n of c.nodes) types.set(n.type, (types.get(n.type) ?? 0) + 1);
      const doc = insertComponent(createBlankDocument(), c.id).doc;
      const strip = (id) => (id.startsWith(`${c.id}-`) ? id.slice(c.id.length + 1) : id);
      const knobIds = new Set(c.knobs.map(k => `ctl-${c.id}-${k.id}`));
      const rows = doc.controls.map(k => {
        const kind = knobIds.has(k.id) ? 'knob' : 'automatic';
        const drives = k.bindings.map(b => `${strip(b.nodeId)}.${b.parameter}${b.axis !== undefined ? `[${'xyz'[b.axis]}]` : ''}${b.scale && b.scale !== 1 ? ` ×${num(b.scale)}` : ''}${b.offset ? ` +${num(b.offset)}` : ''}`).join(', ');
        return [code(k.id), k.label, kind, k.type, unitText(k.unit), code(fmtValue(k.default)), range(k.min, k.max, k.step) + (k.choices ? ` choices ${k.choices.join('/')}` : ''), k.editPolicy, k.swatch ? `picker, swatch ${k.swatch}` : k.type === 'color' ? 'picker (#RRGGBB)' : '', drives];
      });
      body.push(`### ${title}\n\n**${c.label}** — ${c.description}\n\n` +
        `- Family: ${f}; ${componentPlacement(c.id)}.\n- Duration: ${c.durationTicks} ticks (${num(c.durationTicks / TICKS_PER_SECOND)} s) minimum; the document grows to fit it.\n` +
        `- Size: ${c.nodes.length} nodes, ${c.edges.length} links${c.anchors.length ? `; extra anchors: ${c.anchors.map(a => a.id).join(', ')}` : ''}.\n` +
        `- Node types used: ${[...types].sort((a, b) => a[0].localeCompare(b[0])).map(([t, n]) => `${t}${n > 1 ? ` ×${n}` : ''}`).join(', ')}.\n` +
        `- Add with \`vfx_add_component\` (component "${c.id}") or open as a new effect with \`vfx_new_document\` component="${c.id}". Set a control with \`vfx_set_control\` using its **control id** (below; ids shown for an effect where the component keeps its default prefix "${c.id}", a second copy gets "${c.id}-2").\n\n` +
        `**Controls**\n\n${table(['control id', 'label', 'kind', 'type', 'unit', 'default', 'range', 'edit', 'colour', 'drives (node.parameter)'], rows)}`);
    }
  }
  const intro = `All ${comps.length} ready-made components. A component is a complete pre-wired node graph inserted into an effect; you change it through its published controls (knobs), not by editing its nodes. Every control below was read from an actual insertion into a blank document, so ids, types and ranges are exactly what the tools will report.

Controls come in two kinds:
- **automatic**: every component gets **Start at** (\`ctl-<id>-start-at\`, ticks: delays the whole component so it can play after another one; becomes "Delay after event" when started from an event), **Colour** (\`ctl-<id>-colour-shift\`: rotates every colour of the component around the colour wheel in degrees -180..180; the editor shows it as a colour picker of the swatch shown, and \`vfx_set_control\` also accepts a "#RRGGBB" string) and, when the component has two or more visual parts, one colour picker per part (\`ctl-<id>-colour-<part>\`: Flame, Embers, Smoke & dust, Flash & rings, Light...; each takes a "#RRGGBB" and recolours only that part).
- **knob**: the component's own published controls (count, speed, size, length...), each bound to one or more node parameters. "drives" lists \`node.parameter\` (axis in brackets for one component of a vector, ×scale and +offset when the knob value is scaled before it reaches the parameter).

Control ids shown use the default insertion prefix (the component id). Ranges are widened/narrowed so every bound parameter stays inside its own limits.`;
  save('components.md', file('components.md', 'Component reference', intro, toc, body.join('\n')));
}

