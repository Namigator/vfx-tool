// ---------------------------------------------------------------- formatting helpers
const num = (n) => (Number.isInteger(n) ? String(n) : String(Number(n.toPrecision(6))));
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ').trim();
const code = (s) => '`' + String(s).replace(/`/g, "'").replace(/\|/g, '\\|') + '`';
const slug = (h) => h.toLowerCase().replace(/[^a-z0-9 _-]/g, '').trim().replace(/ /g, '-');
const rel = (p) => relative(ROOT, p).split('\\').join('/');
const isColor = (v) => v && typeof v === 'object' && typeof v.srgb === 'string';

function fmtValue(v) {
  if (v === undefined || v === null) return '—';
  if (typeof v === 'number') return num(v);
  if (typeof v === 'boolean') return String(v);
  if (typeof v === 'string') return v === '' ? '""' : v;
  if (Array.isArray(v)) return `[${v.map(fmtValue).join(', ')}]`;
  if (isColor(v)) return v.srgb + (v.alpha === 1 ? '' : `@${num(v.alpha)}`);
  if (Array.isArray(v.keys)) return `curve ${v.domain}/${v.interpolation}: ${v.keys.map(k => `${num(k.x)}:${num(k.y)}`).join(' ')}`;
  if (Array.isArray(v.stops)) return `gradient: ${v.stops.map(s => `${num(s.position)}:${fmtValue(s.color)}`).join(' ')}`;
  return JSON.stringify(v);
}
const range = (min, max, step) => (min === undefined && max === undefined ? '—' : `${min === undefined ? '' : num(min)}..${max === undefined ? '' : num(max)}${step !== undefined ? ` step ${num(step)}` : ''}`);
const unitText = (u) => (u === 'none' || !u ? '—' : u);

function table(head, rows) {
  if (!rows.length) return '';
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.map(cell).join(' | ')} |`)].join('\n') + '\n';
}

function file(name, title, intro, tocEntries, body) {
  const toc = tocEntries.map(([label, anchor, depth = 0]) => `${'  '.repeat(depth)}- [${label}](#${anchor})`).join('\n');
  return `<!-- ${BANNER} -->\n> ${BANNER}\n\n# ${title}\n\n${intro.trim()}\n\n## Contents\n\n${toc}\n\n${body.trim()}\n`;
}
const written = [];
function save(name, text) {
  mkdirSync(OUT, { recursive: true });
  writeFileSync(join(OUT, name), text.replace(/\r\n/g, '\n'));
  written.push([name, text.split('\n').length, Buffer.byteLength(text)]);
}

