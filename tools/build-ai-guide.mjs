function buildLimits() {
  const files = walk(join(ROOT, 'src'), ['.ts', '.tsx']).filter(p => !p.endsWith('.generated.ts'));
  const all = new Map(), perFile = [];
  for (const p of files) {
    const lines = readFileSync(p, 'utf8').split(/\r?\n/);
    lines.forEach((line, i) => {
      if (/^\s*(\/\/|\*|\/\*)/.test(line) || !/\bconst\b/.test(line)) return;
      const trailing = line.match(/\/\/\s*(.+)$/)?.[1]?.trim();
      const src = line.replace(/\/\/.*$/, '');
      for (const m of src.matchAll(/\b([A-Z][A-Z0-9_]+)\s*(?::[^=]+)?=\s*([^,;]+?)\s*(?=,\s*[A-Z][A-Z0-9_]*\s*(?::[^=]+)?=|;|$)/g)) {
        if (/[a-z]{3}\s*\(/.test(m[2]) && !/Math\.floor/.test(m[2])) continue;
        if (!all.has(m[1])) all.set(m[1], m[2]);
        if (/^(DEFAULT_)?(MAX|MIN)_/.test(m[1])) {
          const prev = lines[i - 1]?.trim() ?? '';
          const before = /^(\/\*\*|\/\/)/.test(prev) ? prev.replace(/^(\/\*\*|\/\/)\s*/, '').replace(/\s*\*\/$/, '') : '';
          perFile.push({ name: m[1], expr: m[2], file: rel(p), line: i + 1, comment: trailing || before, order: perFile.length });
        }
      }
    });
  }
  const evalExpr = (expr, depth = 0) => {
    if (depth > 8) return undefined;
    let e = expr.replace(/_(?=\d)/g, '').replace(/(\d)_(?=\d)/g, '$1').replace(/\bMath\.floor\b/g, 'F');
    let failed = false;
    e = e.replace(/\b[A-Za-z_][A-Za-z0-9_]*\b/g, id => {
      if (id === 'F' || /^0x/i.test(id)) return id;
      if (!all.has(id)) { failed = true; return id; }
      const v = evalExpr(all.get(id), depth + 1);
      if (v === undefined) failed = true;
      return `(${v})`;
    });
    if (failed || !/^[\dA-Fa-fxX.\s*+\/()\-F]+$/.test(e)) return undefined;
    try { const v = Function('F', `"use strict"; return (${e});`)(Math.floor); return Number.isFinite(v) ? Number(Number(v).toPrecision(10)) : undefined; } catch { return undefined; }
  };
  const seen = new Set();
  const rows = perFile.filter(r => { const k = r.name; if (seen.has(k)) return false; seen.add(k); return true; }).map(r => {
    const value = evalExpr(r.expr);
    const meaning = CURATED[r.name] ?? r.comment;
    if (!meaning) gaps.limits.push(`${r.name} (${r.file}:${r.line})`);
    return { ...r, value: value === undefined ? r.expr : value, meaning };
  });
  const toc = [], body = [];
  const groups = LIMIT_GROUPS.map(([name, test]) => ({ name, list: rows.filter(r => test(r.file)) }));
  const rest = rows.filter(r => !LIMIT_GROUPS.some(([, t]) => t(r.file)));
  if (rest.length) groups.push({ name: 'Other', list: rest });
  const evalOf = (n) => rows.find(r => r.name === n)?.value;
  const headline = [
    ['Live particles at once', evalOf('DEFAULT_MAX_LIVE_PARTICLES'), 'Peak of (rate x lifetime + bursts alive); checked at compile (BUDGET_EXCEEDED).'],
    ['Particles born per effect', evalOf('DEFAULT_MAX_TOTAL_BIRTHS'), 'Total births over the whole effect.'],
    ['Burst events per emitter', evalOf('DEFAULT_MAX_BURST_EVENTS'), 'Trigger events considered by one emitter.'],
    ['Effect duration', `${evalOf('MAX_DURATION_TICKS')} ticks (${evalOf('MAX_EFFECT_SECONDS')} s)`, 'Minimum 1 tick; longer is rejected.'],
    ['Active lights', evalOf('MAX_ACTIVE_LIGHTS'), 'PointLights drawn at once in the preview.'],
    ['Paths per tick / branches', `${evalOf('MAX_PREVIEW_PATHS')} / ${evalOf('MAX_BRANCH_COUNT')}`, 'Beam/bolt/ring paths evaluated per tick; BranchPath branch count cap.'],
    ['Mesh pieces / triangles per frame', `${evalOf('MAX_MESH_INSTANCES')} / ${evalOf('MAX_MESH_TRIANGLES')}`, 'Preview MeshRenderer budget.'],
    ['Roblox export mesh pieces', evalOf('MAX_MESH_PIECES'), 'Parts one export may animate.'],
    ['Imported texture', `${evalOf('MAX_TEXTURE_BYTES') / 1048576} MiB, ${evalOf('MAX_TEXTURE_SIDE')} px per side`, 'Larger is rejected with IMPORT_LIMIT.'],
    ['Imported GLB mesh', `${evalOf('MAX_MESH_BYTES') / 1048576} MiB, ${MESH_LIMITS.triangles} triangles, ${MESH_LIMITS.materials} materials, ${MESH_LIMITS.primitives} primitives`, 'Self-contained GLB 2.0 only; larger is rejected with IMPORT_LIMIT.'],
    ['Document JSON', `${evalOf('MAX_JSON_BYTES') / 1048576} MiB`, 'Larger files are rejected before parsing.'],
  ];
  toc.push(['Headline limits', 'headline-limits']);
  body.push(`## Headline limits

The ones that matter most when building effects.

${table(['limit', 'value', 'meaning'], headline.map(h => [h[0], String(h[1]), h[2]]))}`);
  for (const g of groups) {
    if (!g.list.length) continue;
    toc.push([g.name, slug(g.name)]);
    body.push(`## ${g.name}\n\n${table(['constant', 'value', 'meaning', 'defined in'], g.list.map(r => [code(r.name), typeof r.value === 'number' ? num(r.value) : code(r.value), r.meaning || '—', r.file]))}`);
  }
  const intro = `Hard limits and budgets, collected from the MAX_*/MIN_* constants in src/ (values are evaluated from the source, so they are current). Exceeding a limit is rejected with a diagnostic (usually BUDGET_EXCEEDED, IMPORT_LIMIT or INVALID_VALUE), never silently clamped, unless the meaning says otherwise. Time is in ticks: 60 ticks = 1 second. Per-parameter ranges (Emitter burst <= 4096, rate <= 4096, speed <= 100 m/s...) are listed with each node in nodes.md, not here. A constant defined in several files (for example MAX_DURATION_TICKS) has the same value everywhere.`;
  save('limits.md', file('limits.md', 'Limits and budgets', intro, toc, body.join('\n')));
}

