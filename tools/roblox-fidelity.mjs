#!/usr/bin/env node
// Editor-vs-Roblox fidelity check with a MATCHED camera.
//   node tools/roblox-fidelity.mjs --doc work/packs/x/source/a.vfx.json --model work/packs/x/roblox/A.rbxmx
//        [--ticks 10,30,60] [--cam x,y,z --look x,y,z] [--fov 45] [--out work/fidelity/<name>] [--editor http://127.0.0.1:5174]
//        [--floor Fabric|SmoothPlastic|...]  (default matte Fabric like the editor floor: on glossy SmoothPlastic each
//        PointLight shows as a long vertical specular streak, which read as a broken effect 2026-10-17)
// 1. Editor: headless Chrome renders capture.html at each tick with the camera (meters, editor world space).
// 2. Roblox: a temporary place (rojo) plays the exported model at the origin with the same camera converted to studs
//    ((p - origin) * STUDS_PER_METER, origin = Source anchor over the floor, exactly like the exporter), records it
//    in Studio (~/.claude/tools/studio-record.ps1) and syncs ticks on a magenta flash that ends the frame play starts.
// 3. Writes side-by-side frames, a sheet (editor | roblox per tick) and metrics.json (luma, bright area, bbox).
// Needs: vite dev server, Chrome, rojo, ffmpeg, Roblox Studio. The capture is the primary monitor: do not use the PC.
import { spawnSync } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { basename, join, resolve } from 'node:path';

const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i < 0 ? d : args[i + 1]; };
const vec = s => s ? s.split(',').map(Number) : undefined;
const docPath = opt('doc'), modelPath = opt('model');
if (!docPath || !modelPath) { console.error('usage: roblox-fidelity.mjs --doc <doc.vfx.json> --model <effect.rbxmx> [--ticks a,b] [--cam x,y,z --look x,y,z]'); process.exit(2); }
const ROOT = resolve(import.meta.dirname, '..');
const doc = JSON.parse(readFileSync(docPath, 'utf8'));
const S = 1 / 0.28;
const anchor = id => doc.anchors.find(a => a.id === id)?.position;
const src = anchor('source') ?? [0, 0, 0], tgt = anchor('target') ?? src;
const origin = [src[0], 0, src[2]];
const dur = doc.durationTicks;
const ticks = (opt('ticks') ?? [0.1, 0.25, 0.45, 0.7].map(f => Math.round(dur * f)).join(',')).split(',').map(Number);
// Default camera: side view of the Source→Target span, a little above, far enough to hold it all at 45°.
const mid = [(src[0] + tgt[0]) / 2, Math.max(1, (src[1] + tgt[1]) / 2), (src[2] + tgt[2]) / 2];
const span = Math.max(3, Math.hypot(tgt[0] - src[0], tgt[1] - src[1], tgt[2] - src[2]));
const look = vec(opt('look')) ?? mid;
const cam = vec(opt('cam')) ?? [mid[0], mid[1] + span * 0.35, mid[2] + span * 1.25];
const fov = Number(opt('fov', 45));
const tweak = Object.fromEntries((opt('tweak', '')).split(',').filter(Boolean).map(kv => kv.split('=')).map(([k, v]) => [k, Number(v)]));
const name = opt('name', basename(modelPath, '.rbxmx')) + (opt('tweak') ? '-' + opt('tweak').replace(/[=,]/g, '') : '');
const out = resolve(opt('out', join(ROOT, 'work', 'fidelity', name)));
const editor = opt('editor', 'http://127.0.0.1:5174');
mkdirSync(out, { recursive: true });
const W = 640, H = 360;
const run = (cmd, a, o = {}) => { const r = spawnSync(cmd, a, { encoding: o.encoding ?? 'utf8', maxBuffer: 1 << 30, ...o }); if (r.status !== 0) throw new Error(`${cmd} failed: ${(r.stderr || r.stdout || '').toString().slice(-800)}`); return r.stdout; };
const chrome = ['C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Google/Chrome/Application/chrome.exe'].find(existsSync);

// ---- 1. editor frames ----
const docUrl = '/' + resolve(docPath).slice(ROOT.length + 1).replace(/\\/g, '/');
for (const t of [...ticks, 'plate']) {
  rmSync(join(out, `editor-${t}.png`), { force: true });
  // The plate solos a node that does not exist: same camera and stage, no effect (for background subtraction).
  const url = `${editor}/capture.html?doc=${encodeURIComponent(docUrl)}&tick=${t === 'plate' ? 0 : t}&cam=${cam.join(',')}&look=${look.join(',')}&fov=${fov}${t === 'plate' ? '&solo=__none__' : ''}`;
  const png = join(out, `editor-${t}.png`);
  // Chrome sometimes writes the screenshot and then never exits: a timeout plus the file is success.
  spawnSync(chrome, ['--headless=new', '--hide-scrollbars', `--window-size=${W},${H}`, '--virtual-time-budget=20000', `--screenshot=${png}`, url], { timeout: 60_000, killSignal: 'SIGKILL' });
  if (!existsSync(png)) throw new Error(`editor capture failed at tick ${t}`);
}

// ---- 2. Roblox place + recording ----
const toStuds = p => p.map((v, i) => (v - origin[i]) * S);
const rc = toStuds(cam), rl = toStuds(look);
const place = join(out, 'place');
mkdirSync(join(place, 'effects'), { recursive: true });
copyFileSync(modelPath, join(place, 'effects', 'Effect.rbxmx'));
const lua = `-- generated by tools/roblox-fidelity.mjs
local Players = game:GetService("Players")
local StarterGui = game:GetService("StarterGui")
local RunService = game:GetService("RunService")
local player = Players.LocalPlayer
pcall(function() StarterGui:SetCoreGuiEnabled(Enum.CoreGuiType.All, false) end)
pcall(function() StarterGui:SetCore("TopbarEnabled", false) end)
local function park(char) local r = char:WaitForChild("HumanoidRootPart"); r.Anchored = true; r.CFrame = CFrame.new(0, -60, -400) end
if player.Character then task.spawn(park, player.Character) end
player.CharacterAdded:Connect(park)
local shot = CFrame.lookAt(Vector3.new(${rc.join(', ')}), Vector3.new(${rl.join(', ')}))
RunService:BindToRenderStep("FidelityCamera", Enum.RenderPriority.Last.Value, function()
	local c = workspace.CurrentCamera
	c.CameraType = Enum.CameraType.Scriptable
	c.FieldOfView = ${fov}
	c.CFrame = shot
end)
local gui = Instance.new("ScreenGui"); gui.IgnoreGuiInset = true; gui.ResetOnSpawn = false
local flash = Instance.new("Frame"); flash.Size = UDim2.fromScale(1, 1); flash.BackgroundColor3 = Color3.fromRGB(255, 0, 255); flash.BorderSizePixel = 0; flash.Visible = false; flash.Parent = gui
gui.Parent = player:WaitForChild("PlayerGui")
local template = game:GetService("ReplicatedStorage"):WaitForChild("Effects"):WaitForChild("Effect")
if not player.Character then player.CharacterAdded:Wait() end
task.wait(4)
flash.Visible = true
task.wait(0.5)
local model = template:Clone()
-- Experimental mapping tweaks (--tweak gamma=2.2,bright=1.5,beam=2): opacity a -> a^(1/gamma), Brightness x bright.
local G, B, BB = ${tweak.gamma ?? 1}, ${tweak.bright ?? 1}, ${tweak.beam ?? tweak.bright ?? 1}
local function remap(seq)
	local keys = {}
	for _, k in ipairs(seq.Keypoints) do
		local a = math.clamp(1 - k.Value, 0, 1) ^ (1 / G)
		table.insert(keys, NumberSequenceKeypoint.new(k.Time, 1 - a, k.Envelope))
	end
	return NumberSequence.new(keys)
end
for _, d in ipairs(model:GetDescendants()) do
	if d:IsA("ParticleEmitter") and string.sub(d.Name, -5) == "_halo" then
		local hs, ha = ${tweak.halosize ?? 1}, ${tweak.haloalpha ?? 1}
		local sk, tk = {}, {}
		for _, k in ipairs(d.Size.Keypoints) do table.insert(sk, NumberSequenceKeypoint.new(k.Time, k.Value * hs, k.Envelope * hs)) end
		for _, k in ipairs(d.Transparency.Keypoints) do table.insert(tk, NumberSequenceKeypoint.new(k.Time, 1 - math.clamp((1 - k.Value) * ha, 0, 1), k.Envelope)) end
		d.Size = NumberSequence.new(sk); d.Transparency = NumberSequence.new(tk)
		if ${tweak.halored ?? 0} == 1 then d.Color = ColorSequence.new(Color3.new(1, 0, 0)); d.Transparency = NumberSequence.new(0); d.LightEmission = 0 end
		print("HALO", d:GetFullName(), d.Rate, d.Enabled)
	end
	if d:IsA("ParticleEmitter") then
		if ${tweak.squash ?? -1} == 0 then d.Squash = NumberSequence.new(0) end
		if ${tweak.face ?? 0} == 1 then d.Orientation = Enum.ParticleOrientation.FacingCamera end
		if ${tweak.tex ?? 1} == 0 then d.Texture = "rbxasset://textures/particles/sparkles_main.dds" end
	end
	if d:IsA("ParticleEmitter") and d.LightEmission > 0 then
		d.Transparency = remap(d.Transparency); d.Brightness = d.Brightness * B
	elseif d:IsA("PointLight") and ${tweak.light ?? 1} == 0 then
		d.Range = 0
	elseif d:IsA("Beam") then
		d.Brightness = d.Brightness * BB
	end
end
model.Parent = workspace
local EffectPlayer = require(model:WaitForChild("EffectPlayer"))
RunService.RenderStepped:Wait()
flash.Visible = false
EffectPlayer.play(model, CFrame.new(0, 0, 0))
-- Culling probes (--tweak bounds=1,rig=1): small invisible parents near the floor get culled (2026-10-18). bounds=1 moves
-- every ParticleEmitter onto an Attachment (same point) and grows its Part to 6 studs; rig=1 grows the beam rig.
if ${tweak.bounds ?? 0} == 1 then
	for _, em in ipairs(model:GetDescendants()) do
		if em:IsA("ParticleEmitter") and em.Parent:IsA("BasePart") then
			local part = em.Parent
			local att = Instance.new("Attachment"); att.Parent = part; em.Parent = att
			part.Size = Vector3.new(6, 6, 6)
		end
	end
end
if ${tweak.rig ?? 0} == 1 then
	local rig = model:FindFirstChild("_BeamRig"); if rig then rig.Size = Vector3.new(80, 8, 80) end
end
print("FIDELITY_PLAY")
`;
mkdirSync(join(place, 'src'), { recursive: true });
writeFileSync(join(place, 'src', 'Fidelity.client.lua'), lua);
writeFileSync(join(place, 'default.project.json'), JSON.stringify({
  name: 'Fidelity', tree: {
    $className: 'DataModel',
    Workspace: { $className: 'Workspace', $ignoreUnknownInstances: true,
      // Rojo writes a Part's "Position" but Studio ignores it on load (CFrame is the serialized property): the floor sat
      // at the origin, its top 1 stud up, and swallowed everything lower (Summon riders, ground rings; 2026-10-18).
      ...(opt('floor') === 'None' ? {} : { Floor: { $className: 'Part', $properties: { Anchored: true, Locked: true, Size: [400, 2, 400], CFrame: { CFrame: { position: [0, -1, 0], orientation: [[1, 0, 0], [0, 1, 0], [0, 0, 1]] } }, Color: [0.09, 0.09, 0.11], Material: opt('floor', 'Fabric') } } }),
      SpawnLocation: { $className: 'SpawnLocation', $properties: { Anchored: true, Size: [6, 1, 6], CFrame: { CFrame: { position: [0, 0.5, 150], orientation: [[1, 0, 0], [0, 1, 0], [0, 0, 1]] } }, Neutral: true, Transparency: 1 } } },
    // A typical dark scene with Roblox's DEFAULT bloom: what a buyer gets without tuning anything.
    Lighting: { $className: 'Lighting', $ignoreUnknownInstances: true,
      $properties: { Technology: 'Future', ClockTime: 0, Brightness: 1, Ambient: [0.1, 0.1, 0.12], OutdoorAmbient: [0.1, 0.1, 0.12], GlobalShadows: false },
      Bloom: { $className: 'BloomEffect', $properties: { Intensity: 1, Size: 24, Threshold: 2 } } },
    ReplicatedStorage: { $className: 'ReplicatedStorage', $ignoreUnknownInstances: true, Effects: { $path: 'effects' } },
    StarterPlayer: { $className: 'StarterPlayer', $ignoreUnknownInstances: true,
      StarterPlayerScripts: { $className: 'StarterPlayerScripts', $ignoreUnknownInstances: true, Fidelity: { $path: 'src/Fidelity.client.lua' } } },
  },
}, null, 2));
const env = { ...process.env, PATH: `${process.env.PATH};${join(homedir(), '.cargo', 'bin')}` };
run('rojo', ['build', join(place, 'default.project.json'), '-o', join(place, 'Fidelity.rbxl')], { env });
const video = join(out, 'roblox.mp4');
const seconds = Math.ceil(12 + dur / 60 + 1); // Play -> character -> 4 s settle -> 0.5 s flash -> effect
if (!(args.includes('--reuse') && existsSync(video))) run('powershell', ['-ExecutionPolicy', 'Bypass', '-File', join(homedir(), '.claude', 'tools', 'studio-record.ps1'), '-Place', join(place, 'Fidelity.rbxl'), '-Out', video, '-Seconds', String(seconds), '-LoadWait', '25', '-Quality', String(opt('quality', 21))], { stdio: 'inherit', encoding: 'utf8' });

// ---- 3. sync + frames + metrics ----
const VIEW = opt('crop', '1330:748:282:208'); // 16:9 centre of the maximised Studio game view (1920x1080 monitor)
const probe = run('ffmpeg', ['-v', 'error', '-i', video, '-fps_mode', 'passthrough', '-vf', `crop=${VIEW},scale=1:1`, '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'], { encoding: 'buffer' });
let last = -1;
for (let i = 0; i < probe.length / 3; i++) { const [r, g, b] = [probe[i * 3], probe[i * 3 + 1], probe[i * 3 + 2]]; if (r > 170 && b > 170 && g < 90) last = i; }
if (last < 0) throw new Error('sync flash not found in the recording');
const t0 = last + 1;
const frames = probe.length / 3;
const missing = ticks.filter(t => t0 + t >= frames);
if (missing.length) throw new Error(`recording ends at frame ${frames}, sync at ${t0}: ticks ${missing} not recorded`);
const Y = (buf, i) => (0.2126 * buf[i * 3] + 0.7152 * buf[i * 3 + 1] + 0.0722 * buf[i * 3 + 2]) / 255;
/** What the effect adds over its empty plate: mean added luma, area that got >0.1 brighter, bbox of that area. */
const added = (buf, plate) => { let sum = 0, area = 0, peak = 0, x0 = W, y0 = H, x1 = -1, y1 = -1;
  for (let i = 0; i < W * H; i++) { const d = Math.max(0, Y(buf, i) - Y(plate, i)); sum += d; peak = Math.max(peak, d);
    if (d > 0.1) { area++; const x = i % W, yy = (i / W) | 0; x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, yy); y1 = Math.max(y1, yy); } }
  return { addedLuma: +(sum / (W * H)).toFixed(4), litArea: +(area / (W * H)).toFixed(4), peak: +peak.toFixed(3), bbox: x1 < 0 ? null : [x0, y0, x1, y1] }; };
const raw = (file, vf) => run('ffmpeg', ['-v', 'error', '-i', file, '-vf', vf, '-frames:v', '1', '-f', 'rawvideo', '-pix_fmt', 'rgb24', '-'], { encoding: 'buffer' });
run('ffmpeg', ['-v', 'error', '-y', '-i', video, '-vf', `select=eq(n\\,${Math.max(0, t0 - 45)}),crop=${VIEW},scale=${W}:${H}`, '-frames:v', '1', join(out, 'roblox-plate.png')]);
const plates = { e: raw(join(out, 'editor-plate.png'), `scale=${W}:${H}`), r: raw(join(out, 'roblox-plate.png'), 'null') };
const metrics = [];
for (const t of ticks) {
  run('ffmpeg', ['-v', 'error', '-y', '-i', video, '-vf', `select=eq(n\\,${t0 + t}),crop=${VIEW},scale=${W}:${H}`, '-frames:v', '1', join(out, `roblox-${t}.png`)]);
  const e = added(raw(join(out, `editor-${t}.png`), `scale=${W}:${H}`), plates.e), r = added(raw(join(out, `roblox-${t}.png`), 'null'), plates.r);
  metrics.push({ tick: t, editor: e, roblox: r, lumaRatio: e.addedLuma ? +(r.addedLuma / e.addedLuma).toFixed(2) : null, areaRatio: e.litArea ? +(r.litArea / e.litArea).toFixed(2) : null });
}
const inputs = ticks.flatMap(t => ['-i', join(out, `editor-${t}.png`), '-i', join(out, `roblox-${t}.png`)]);
const rows = ticks.map((_, k) => `[${2 * k}:v]scale=${W}:${H}[e${k}];[${2 * k + 1}:v]scale=${W}:${H}[r${k}];[e${k}][r${k}]hstack[row${k}]`).join(';');
run('ffmpeg', ['-v', 'error', '-y', ...inputs, '-filter_complex', ticks.length > 1 ? `${rows};${ticks.map((_, k) => `[row${k}]`).join('')}vstack=${ticks.length}` : rows.replace('[row0]', ''), join(out, 'sheet.png')]);
writeFileSync(join(out, 'metrics.json'), JSON.stringify({ doc: docPath, model: modelPath, camera: { cam, look, fov, robloxCam: rc, robloxLook: rl }, syncFrame: t0, metrics }, null, 2));
console.log(JSON.stringify({ sheet: join(out, 'sheet.png'), metrics: metrics.map(m => ({ tick: m.tick, lumaRatio: m.lumaRatio, areaRatio: m.areaRatio, editor: m.editor, roblox: m.roblox })) }, null, 1));
